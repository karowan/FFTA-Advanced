import fs from 'node:fs';
import path from 'node:path';
import {root,cleanROM,sha1,missions,nameAt} from '../src/rom-data.mjs';

const rom=cleanROM();
const design=JSON.parse(fs.readFileSync(path.join(root,'notes/job-theme-audit.json')));
const equipment=JSON.parse(fs.readFileSync(path.join(root,'notes/equipment-acquisition.json')));
const output=path.join(root,'build/expansion');
fs.mkdirSync(output,{recursive:true});
const raceIds={Human:1,Bangaa:2,'Nu Mou':3,Viera:4,Moogle:5};
const specs=[
  ['Human','Samurai','SAM',[[4,2],[6,1]]],
  ['Human','Dark Knight','DRK',[[3,2],[8,2]]],
  ['Bangaa','Viking','VIK',[[13,3],[17,1]]],
  ['Bangaa','Dark Knight','DRK',[[16,2],[18,1]]],
  ['Nu Mou','Chemist','CHM',[]],
  ['Nu Mou','Geomancer','GEO',[[27,2],[21,3]]],
  ['Moogle','Chemist','CHM',[]],
  ['Moogle','Bard','BRD',[[36,2],[40,2]]],
  ['Viera','Dancer','DNC',[[28,2],[31,2]]],
  ['Viera','Mystic Knight','MYK',[[30,2],[29,2]]],
];
const jobs=specs.map(([race,name,group,prerequisites],i)=>({id:0x74+i,race:raceIds[race],raceName:race,name,group,nameId:753+85+i,prerequisites:prerequisites.map(([jobId,actions])=>({jobId,actions,job:nameAt(rom,0x526680,rom.readUInt16LE(0x521a14+52*jobId))}))}));
jobs.push({id:2,race:1,raceName:'Human',name:'Soldier',group:'SLD-AX',existing:true},
          {id:16,race:2,raceName:'Bangaa',name:'Gladiator',group:'GLD-AX',existing:true});
const races=Object.entries(raceIds).map(([name,id])=>{
  const base=rom.readUInt32LE(0x51ba84+4*id)&0x1ffffff;
  let count=1;
  while(rom.subarray(base+8*count,base+8*count+8).some(x=>x!==0))count++;
  return {id,name,base,nativeCount:count,firstNew:id===1?0x90:count,next:id===1?0x90:count};
});
// The randomizer's 0x15A count omits the final native Blank Card action.
// Preserve all347 rows through553E70 before allocating any expansion action.
const nativeActionCount=(0x553e70-0x55187c)/28;
if(nativeActionCount!==347 || nameAt(rom,0x5567f0,rom.readUInt16LE(0x55187c+346*28))!=='Blank Card')
  throw Error('Native action domain boundary changed');
const counters={Action:nativeActionCount,Support:0x80,Reaction:0x80,Combo:0x80};
const types={Action:1,Support:3,Reaction:2,Combo:5};
const lessons=design.abilities.map((lesson,i)=>{
  const group=lesson.id.replace(/-[ASRC]\d+$/,'');
  const owners=jobs.filter(j=>j.group===group);
  if(!owners.length||lesson.ap%10||lesson.ap/10>127)throw Error(`Unencodable lesson ${lesson.id}`);
  return {...lesson,globalAbilityId:counters[lesson.type]++,nativeType:types[lesson.type],nameId:767+i,
    owners:owners.map(job=>({jobId:job.id,race:job.race,abilityIndex:races.find(r=>r.id===job.race).next++}))};
});
const items=equipment.items.map((item,i)=>({...item,romItemId:376+i,nameId:753+i,
  teaching:item.lessons.flatMap(l=>lessons.find(a=>a.id===l.id).owners.map(o=>({...o,lesson:l.id})))}));
const internalGates={S0:null,S1:7,S2:13,S3:19};
const ms=missions(rom);
const stages=equipment.stages.map(s=>{
  const missionIndex=internalGates[s.id];
  if(missionIndex!==null&&ms[missionIndex].name!==s.missionName)throw Error(`Wrong gate ${s.id}`);
  return {...s,missionIndex};
});
for(const race of races){
  race.totalCount=race.next;delete race.next;
  if(race.id!==1&&race.totalCount>0x8e)throw Error(`Native AP overflow: ${race.name}`);
}
if(lessons.length!==129||items.length!==85||races[0].totalCount!==0xb2)throw Error('Approved capacity changed');
const registry={schema:1,designVersion:design.version,status:'Allocated IDs and contracts; not a claim of implemented effects',
  baseSha1:sha1(rom),designSha1:sha1(fs.readFileSync(path.join(root,'notes/job-theme-audit.json'))),equipmentSha1:sha1(fs.readFileSync(path.join(root,'notes/equipment-acquisition.json'))),
  races,jobs,lessons,items,stages,
  actionDomain:{nativeCount:nativeActionCount,firstNew:nativeActionCount,totalCount:counters.Action},
  storage:{inventoryStart:0x02001940,inventoryBytes:512,sidecarStart:0x02001b40,sidecarBytes:816,sidecarStride:34,metadataStart:0x02001e70,metadataBytes:172,end:0x02001f1c},
  unresolved:['Equipment IDs above375 require context-preserving item/reward hooks','New support/reaction/combo dispatch must handle allocated IDs','Every Human AP accessor and unit lifecycle must support sidecar']};
fs.writeFileSync(path.join(output,'registry.json'),JSON.stringify(registry,null,2));
const symbols=lessons.map(a=>`#define FFTA_${a.id.replaceAll('-','_')} ${a.globalAbilityId}u`);
fs.writeFileSync(path.join(output,'ability-ids.inc'),lessons.map(a=>`.equ FFTA_${a.id.replaceAll('-','_')}, ${a.globalAbilityId}`).join('\n')+'\n');
fs.writeFileSync(path.join(output,'registry.h'),`/* Generated by scripts/generate-expansion-registry.mjs. */\n#ifndef FFTA_REGISTRY_H\n#define FFTA_REGISTRY_H\n#define FFTA_MAX_ITEM 460u\n#define FFTA_HUMAN_AP_FIRST 144u\n#define FFTA_HUMAN_AP_COUNT 34u\n${symbols.join('\n')}\n#endif\n`);
const townIds={Cyril:2,Sprohm:3,Muscadet:4,Cadoan:5,'Baguba Port':6};
const stockRows=items.map(item=>{
  const townMask=[item.primaryShop,...item.additionalShops].reduce((mask,town)=>{
    if(townIds[town]===undefined)throw Error('Unknown native town identity: '+town);
    return mask|(1<<townIds[town]);
  },0);
  const mission=internalGates[item.stageId];
  return `    {${item.romItemId},${mission===null?0:mission+0x2ff},${townMask}}`;
});
fs.writeFileSync(path.join(output,'stock.h'),`/* Generated approved additive stock; native town identities. */\n#ifndef FFTA_STOCK_H\n#define FFTA_STOCK_H\n#include <stdint.h>\nstatic const struct {uint16_t item,flag;uint8_t towns;} ffta_stock[85]={\n${stockRows.join(',\n')}\n};\n#endif\n`);
const iconDonors={Sword:1,Saber:32,Knife:74,Rapier:88,Katana:106,Rod:135,Instrument:201,Axe:52};
const jobLessons=jobs.map(job=>{
  const native=job.existing?Array.from({length:rom[0x521a14+52*job.id+47]-rom[0x521a14+52*job.id+46]+1},(_,i)=>rom[0x521a14+52*job.id+46]+i):[];
  const added=lessons.flatMap(a=>a.owners.filter(o=>o.jobId===job.id).map(o=>o.abilityIndex));
  return {...job,indices:[...native,...added]};
});
fs.writeFileSync(path.join(output,'job-lessons.h'),`/* Generated explicit lists: native lessons retained before approved additions. */\n#ifndef FFTA_JOB_LESSONS_H\n#define FFTA_JOB_LESSONS_H\n#include <stdint.h>\n${jobLessons.map(j=>`static const uint8_t ffta_lessons_${j.id}[]={${j.indices.join(',')}};`).join('\n')}\nstatic const struct {uint8_t id,race,count;const uint8_t *indices;} ffta_job_lessons[]={\n${jobLessons.map(j=>`    {${j.id},${j.race},${j.indices.length},ffta_lessons_${j.id}}`).join(',\n')}\n};\n#endif\n`);
fs.writeFileSync(path.join(output,'icons.h'),`/* Native family icon donors; Axe artwork remains an integration task. */\n#include <stdint.h>\nstatic const uint16_t ffta_item_icon_donors[85]={${items.map(i=>{if(!iconDonors[i.category])throw Error('Missing icon donor');return iconDonors[i.category];}).join(',')}};\n`);
console.log(JSON.stringify({jobs:10,lessons:lessons.length,items:items.length,races:races.map(({name,nativeCount,totalCount})=>({name,nativeCount,totalCount})),stages:stages.map(({id,missionIndex})=>({id,missionIndex}))},null,2));
